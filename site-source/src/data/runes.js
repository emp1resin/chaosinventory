// FAQ: a word adds its own effects plus one copy of every rune it contains.
export const runeWordBonuses = Object.fromEntries(
  Object.entries(runesWordAll).map(([word, extra]) => {
    const total = { ...extra }
    for (const rune of word) {
      const [parameter, value] = runesAll[rune]
      total[parameter] = (total[parameter] || 0) + value
    }
    total.url = word.slice(0, 3).toUpperCase() + word.slice(3)
    if (total.url === 'CONquest') total.url = 'CONcuest'
    return [word, total]
  })
)
